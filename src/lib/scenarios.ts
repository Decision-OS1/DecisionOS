export function getScenariosForAgeGroup(ageGroup: AgeGroup | null | undefined): Scenario[] {
  if (!ageGroup) return SCENARIOS;
  const matches = SCENARIOS.filter((s) => s.ageGroups.includes(ageGroup));
  return matches.length > 0 ? matches : SCENARIOS;
}

export function getScenarioForDay(
  dayNumber: number,
  ageGroup?: AgeGroup | null,
): Scenario {
  const pool = getScenariosForAgeGroup(ageGroup);
  return pool[(dayNumber - 1) % pool.length];
}

export function generateAiFeedback(scenario: Scenario, optionId: string): {
  bias: string;
  feedback: string;
} {
  const option = scenario.options.find((o) => o.id === optionId) ?? scenario.options[0];
  const explanation =
    BIAS_EXPLANATIONS[option.bias] ??
    "This choice reveals something interesting about how you weigh this decision.";

  const feedback = `You chose "${option.label}." ${explanation} There's no single right answer here — what matters is noticing the pattern so you can decide on purpose next time.`;

  return { bias: option.bias, feedback };
}
